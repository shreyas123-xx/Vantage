"""
In-memory store keyed by uuid, so a dataset generated by one request can be
referenced by id in later requests (analyze -> predict -> schedule) without
re-uploading it every time. Deliberately simple: swap for Redis/Postgres if
this needs to survive process restarts or run across multiple workers.

Bounded with LRU eviction (OrderedDict, move-to-end on access) so a
long-running demo instance - where every "Generate & analyze" click on the
Drift tab stores two new datasets and an analysis, with no explicit
delete endpoint - doesn't grow memory without limit over a long session.
"""
from __future__ import annotations
from collections import OrderedDict
from threading import Lock
import uuid


class BoundedStore:
    def __init__(self, max_size: int = 200):
        self._data: OrderedDict[str, object] = OrderedDict()
        self._max_size = max_size
        self._lock = Lock()

    def put(self, obj: object) -> str:
        key = str(uuid.uuid4())
        with self._lock:
            self._data[key] = obj
            self._data.move_to_end(key)
            while len(self._data) > self._max_size:
                self._data.popitem(last=False)  # evict least-recently-used
        return key

    def get(self, key: str) -> object:
        with self._lock:
            obj = self._data.get(key)
            if obj is None:
                raise KeyError(f"No entry found for id {key} (it may have expired - "
                                f"this demo store keeps only the most recent entries)")
            self._data.move_to_end(key)
        return obj

    def __len__(self) -> int:
        return len(self._data)


_datasets = BoundedStore(max_size=200)
_analyses = BoundedStore(max_size=200)


def store_dataset(obj) -> str:
    return _datasets.put(obj)


def get_dataset(key: str):
    return _datasets.get(key)


def store_analysis(obj) -> str:
    return _analyses.put(obj)


def get_analysis(key: str):
    return _analyses.get(key)
